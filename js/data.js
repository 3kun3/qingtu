/* 按名称匹配著名景点专属照片 */
function poiSpecificPhoto(name) {
  if (!name) return null;
  for (const item of POI_SPECIFIC_PHOTOS) {
    if (item.kw.some(k => name.includes(k))) return item.url;
  }
  return null;
}

/* 兜底封面：SVG data URI，渐变背景 + 分类 emoji + POI 名。
 * 网络不可用或 CDN 失败时显示，100% 可靠无需下载。 */
function poiFallbackImage(poi) {
  const tag = Object.entries(poi.tags || {}).sort((a, b) => b[1] - a[1])[0];
  const meta = tag ? TAG_META[tag[0]] : null;
  const color = meta ? meta.color : '#5b8ff9';
  const icon = meta ? meta.icon : '📍';
  const name = (poi.name || '').slice(0, 8);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="450" viewBox="0 0 800 450">
    <defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0%" stop-color="${color}" stop-opacity="0.85"/>
      <stop offset="100%" stop-color="${color}" stop-opacity="0.45"/>
    </linearGradient></defs>
    <rect width="800" height="450" fill="url(#g)"/>
    <text x="400" y="210" font-size="90" text-anchor="middle" font-family="sans-serif">${icon}</text>
    <text x="400" y="300" font-size="36" text-anchor="middle" fill="white" font-family="sans-serif" font-weight="bold">${name}</text>
  </svg>`;
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}

