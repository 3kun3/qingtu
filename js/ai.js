/* ---------- 核心调用 ---------- */
async function callAI(messages, opts = {}) {
  const { temperature = 0.7 } = opts;

  if (AI_CFG.mock || !AI_CFG.apiKey) {
    const last = [...messages].reverse().find(m => m.role === 'user');
    const content = last ? last.content : '';
    if (content.includes('润色') || (content.includes('行程') && content.includes('日记'))) {
      return MOCK.polish(opts._plan, opts._profile);
    }
    if (content.includes('介绍') || content.includes('讲解')) {
      return MOCK.explain(opts._poi);
    }
    return mockChatAnswer(content, messages);
  }

  try {
    const res = await fetch(`${AI_CFG.baseUrl}/chat/completions`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', 'Authorization': `Bearer ${AI_CFG.apiKey}` },
      body: JSON.stringify({ model: AI_CFG.model, messages, temperature })
    });
    if (!res.ok) throw new Error('AI API 错误: ' + res.status);
    const data = await res.json();
    return data.choices[0].message.content;
  } catch (e) {
    return 'AI 服务暂时不可用，请稍后再试。当前为演示模式，可继续使用内置知识库。';
  }
}

