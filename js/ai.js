function pickRandom(arr) { return arr[Math.floor(Math.random() * arr.length)]; }

/* 检测用户意图 */
function detectIntent(text) {
  for (const item of INTENTS) {
    if (item.kw.some(k => text.includes(k))) return item.r;
  }
  return null;
}

/* ---------- 智能回答（核心） ---------- */
function mockChatAnswer(text, history) {
  const t = (text || '').trim();
  if (!t) return '请问有什么旅行问题想了解？';

  // 从当前消息 + 历史消息中提取城市（上下文记忆）
  const city = detectCity(t) || (history ? detectCity(history.map(m=>m.content).join(' ')) : null);

  // 1. 问候/感谢/再见
  if (/^(你好|您好|hi|hello|在吗|嗨|哈喽)/i.test(t)) {
    return '你好！我是轻途 AI 助手 👋 可以帮你：\n\n🗺 推荐城市景点和美食\n🌤 查询天气和最佳旅游季节\n💰 预算和住宿建议\n🧭 交通和行程规划\n\n直接问我吧，比如"成都有什么好吃的"～';
  }
  if (/谢谢|感谢|多谢|thanks/i.test(t)) return pickRandom(['不客气！祝你旅途愉快 ✨', '能帮到你真好，还有其他问题随时问～']);
  if (/再见|拜拜|bye|88/i.test(t)) return '再见，期待下次帮你规划旅程 👋';

  // 2. 城市 + 意图组合（最核心，避免答非所问）
  const intent = detectIntent(t);

  if (city && intent) {
    const info = CITY_KB[city][intent];
    if (info) return info;
    // 城市有但该意图没数据，返回城市简介
    return CITY_KB[city].intro;
  }

  // 3. 只有城市（问"XX怎么样"、"XX好玩吗"）
  if (city) {
    const c = CITY_KB[city];
    return `${c.intro}\n\n🍜 ${c.food.split('：')[1]}\n🏛 必去景点：${c.attractions.split('：')[1]}`;
  }

  // 4. 只有意图（问"有什么好吃的"之类，没有指定城市）
  if (intent) {
    return INTENT_KB[intent];
  }

  // 5. 计算
  if (/\d+\s*[\+\-\*\/]\s*\d+/.test(t)) {
    try {
      const expr = t.match(/[\d\s\+\-\*\/\.\(\)]+/)[0];
      const result = Function('"use strict";return (' + expr + ')')();
      return `🧮 ${expr.trim()} = ${result}`;
    } catch (e) {}
  }

  // 6. 日期时间
  if (t.includes('今天') || t.includes('日期') || t.includes('时间') || t.includes('几号')) {
    const now = new Date();
    const week = ['日','一','二','三','四','五','六'][now.getDay()];
    return `📅 今天是 ${now.getFullYear()}年${now.getMonth()+1}月${now.getDate()}日 星期${week}`;
  }

  // 7. 你是谁/能做什么
  if (t.includes('你是谁') || t.includes('你叫什么') || t.includes('能做什么') || t.includes('会什么')) {
    return '我是轻途 AI 助手 🤖 专为旅行设计。我可以：\n\n🗺 推荐20+热门城市的景点、美食、住宿\n🌤 查询各地气候和最佳旅游季节\n💰 预算和花费参考\n🧭 交通建议和行程规划\n👶 亲子/拍照/夜游等专项推荐\n\n告诉我你想去哪里，我帮你做攻略！';
  }

  // 8. 兜底：引导用户给出更具体的问题
  return '我可以帮你解答旅行相关的问题哦 👇\n\n比如：\n• "成都有什么好吃的？"\n• "北京天气怎么样？"\n• "西安住哪里方便？"\n• "3天时间怎么玩杭州？"\n\n告诉我你想去的城市和需求，我来帮你～';
}

